#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const root = path.resolve('public/mohemeokji');
const nutritionPolicy=JSON.parse(fs.readFileSync(path.resolve('scripts/data/nutrition-policy.json'),'utf8'));
const policyFile='meal-nutrition-policy.js';
const policyContent='/* Generated from scripts/data/nutrition-policy.json. */\nwindow.mealNutritionPolicy='+JSON.stringify(nutritionPolicy)+';\n';
const ingredientAvailabilityPolicy=JSON.parse(fs.readFileSync(path.resolve('scripts/data/ingredient-availability-policy.json'),'utf8'));
const ingredientAvailabilityFile='meal-ingredient-availability-policy.js';
const ingredientAvailabilityContent=`/* Generated from scripts/data/ingredient-availability-policy.json. */
(function () {
  const policy=${JSON.stringify(ingredientAvailabilityPolicy)};
  const compact=(value)=>String(value??'').normalize('NFKC').replace(/\\s+/gu,'').trim();
  const isIngredientLike=(value)=>{const raw=String(value??'').trim();return raw.length<=80&&!/[.!?。！？]/u.test(raw);};
  const matches=(recipe)=>{
    const source=Array.isArray(recipe?.ingredients)
      ? recipe.ingredients.map((item)=>item?.ingredient??item?.label).filter(Boolean)
      : Array.isArray(recipe?.detailIngredients) ? recipe.detailIngredients.filter(Boolean) : [];
    const found=[];
    for(const raw of source){
      if(!isIngredientLike(raw)) continue;
      const value=compact(raw);
      for(const rule of policy.excludedIngredients||[]){
        if((rule.excludeAliases||[]).map(compact).some((alias)=>alias&&value.includes(alias))) continue;
        const alias=(rule.aliases||[]).map(compact).find((candidate)=>candidate&&value.includes(candidate));
        if(alias) found.push({key:rule.key,label:String(raw).trim(),matchedAlias:alias,reason:rule.reason});
      }
    }
    return [...new Map(found.map((entry)=>[entry.key,entry])).values()].sort((left,right)=>left.key.localeCompare(right.key,'ko'));
  };
  window.mealIngredientAvailability={policyVersion:policy.policyVersion,market:policy.market,matches,isAvailable:(recipe)=>matches(recipe).length===0};
}());
`;
const evidenceFile='meal-verified-evidence.js';
const evidence=JSON.parse(fs.readFileSync('data/mohemeokji/verified-reviews.json','utf8'));
const evidenceContent='/* Generated by scripts/verify-meal-reviews.mjs; source checks are bound to snapshot and detail hashes. */\nwindow.mealVerifiedEvidence='+JSON.stringify(evidence).replaceAll('<','\\u003c')+';\n';
const assets = ['ontology-recipe-details.js','ontology-recipe-popular.js','meal-package-prices.js','meal-planner-recipe-data.js','meal-data-loader.js','meal-shopping.js',policyFile,ingredientAvailabilityFile,'meal-recommendations.js',evidenceFile];
const assetContent=(file)=>file===policyFile?policyContent:file===ingredientAvailabilityFile?ingredientAvailabilityContent:file===evidenceFile?evidenceContent:fs.readFileSync(path.join(root,file),'utf8');
const version = crypto.createHash('sha256').update(assets.map(assetContent).join('\n')).digest('hex').slice(0,12);
const canonical = fs.readFileSync(path.join(root,'index.html'),'utf8').replace(/(<script src="[^"?]+\.js)\?v=[^"]+("[^>]*>)/g, '$1?v='+version+'$2');
const routes = fs.readdirSync(root,{withFileTypes:true}).filter((entry)=>entry.isDirectory() && fs.existsSync(path.join(root,entry.name,'index.html'))).map((entry)=>entry.name);
const outputs = [[path.join(root,policyFile),policyContent],[path.join(root,ingredientAvailabilityFile),ingredientAvailabilityContent],[path.join(root,evidenceFile),evidenceContent],[path.join(root,'index.html'),canonical]];
for (const route of routes) {
  outputs.push([path.join(root,route,'index.html'),canonical]);
  outputs.push([path.join(root,route,'meal-planner-recipe-data.js'),fs.readFileSync(path.join(root,'meal-planner-recipe-data.js'),'utf8')]);
}
let drift = false;
for (const [file,content] of outputs) {
  if (fs.existsSync(file)&&fs.readFileSync(file,'utf8') === content) continue;
  drift = true;
  if (!process.argv.includes('--check')) fs.writeFileSync(file,content);
}
if (process.argv.includes('--check') && drift) { console.error('Meal page copies or asset versions are stale. Run node scripts/sync-meal-pages.mjs'); process.exitCode=1; }
else console.log(JSON.stringify({pages:routes.length+1,assetVersion:version,mode:process.argv.includes('--check')?'check':'sync'}));
